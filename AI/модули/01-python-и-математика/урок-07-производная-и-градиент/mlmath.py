"""
mlmath — маленькая «библиотека» для урока 1.7 (производная и градиент).

Что внутри:
  derivative(f, x)          — численная производная функции ОДНОЙ переменной
  numerical_gradient(f, p)  — градиент функции НЕСКОЛЬКИХ переменных

Как пользоваться:
  1) Положи этот файл mlmath.py рядом со своим ноутбуком
     (в Colab: слева «Файлы» → загрузить mlmath.py).
  2) В своём коде напиши:
         from mlmath import derivative, numerical_gradient
  3) Пользуйся:
         derivative(lambda x: x**2, 5)   # ~10
"""
import numpy as np


def derivative(f, x, h=1e-4):
    """Наклон (производная) функции f в точке x.

    Идея: берём значение чуть ПРАВЕЕ (x + h) и чуть ЛЕВЕЕ (x - h),
    считаем «подъём / пробег» — это и есть наклон касательной.
    Формула — «центральная разность», она точнее обычной.
    """
    return (f(x + h) - f(x - h)) / (2 * h)


def numerical_gradient(f, point, h=1e-4):
    """Градиент функции f в точке point.

    point — массив чисел (например, np.array([3.0, 4.0])).
    Для КАЖДОЙ координаты двигаем ТОЛЬКО её (остальные не трогаем)
    и считаем частную производную по ней.
    Возвращает массив той же длины — по частной производной на координату.
    """
    grad = np.zeros_like(point)          # «корзинка» под ответ (нули нужной формы)
    for i in range(len(point)):
        p_plus = point.copy()            # копия, чтобы не испортить исходную точку
        p_minus = point.copy()
        p_plus[i] += h                   # сдвигаем ТОЛЬКО i-ю координату вверх
        p_minus[i] -= h                  # и вниз
        grad[i] = (f(p_plus) - f(p_minus)) / (2 * h)
    return grad


# Мини-проверка: запусти файл отдельно (python mlmath.py) — увидишь, что всё работает.
if __name__ == "__main__":
    print("derivative(x^2, 5) =", derivative(lambda x: x ** 2, 5))          # ~10
    g = numerical_gradient(lambda p: p[0] ** 2 + p[1] ** 2,
                           np.array([3.0, 4.0]))
    print("gradient(x^2+y^2, [3,4]) =", g)                                   # ~[6, 8]
