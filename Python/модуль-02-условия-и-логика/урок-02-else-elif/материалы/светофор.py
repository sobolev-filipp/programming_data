# ===== СВЕТОФОР =====
# Показываем, что делать по цвету светофора.
# Здесь elif сравнивает СТРОКУ (цвет), а не число.
# .lower() и .strip() — чтобы подходили "Красный", "КРАСНЫЙ", " красный ".

color = input("Какой горит свет? (красный/жёлтый/зелёный) ").lower().strip()

if color == "красный":
    print("Стой на месте.")
elif color == "жёлтый":
    print("Внимание, приготовься.")
elif color == "зелёный":
    print("Можно идти!")
else:
    print(f"'{color}' — это не цвет светофора.")
