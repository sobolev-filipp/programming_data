# ===== ПУСКАТЬ НА АТТРАКЦИОН? =====
# Контролёр у входа на американские горки.
# Новое в этом уроке: логика and / or / not и тип bool.
#
# Правила парка:
#   - кататься можно с ростом >= 140 см И возрастом >= 10 лет;
#   - НО если рядом взрослый (сопровождение) — рост можно от 120 см;
#   - пускаем, только если НЕ болеешь (по самочувствию).

print("=" * 34)
print("КОНТРОЛЬ: АМЕРИКАНСКИЕ ГОРКИ")
print("=" * 34)

height = int(input("Твой рост (см): "))
age = int(input("Твой возраст: "))
with_adult = input("Рядом взрослый? (да/нет) ").lower().strip() == "да"
feel_ok = input("Хорошо себя чувствуешь? (да/нет) ").lower().strip() == "да"

# bool-переменные хранят True/False — их удобно читать в условии
print(f"[проверка] сопровождение: {with_adult}, самочувствие: {feel_ok}")

# основной допуск по росту и возрасту
solo_ok = height >= 140 and age >= 10
# с сопровождением требования мягче
adult_ok = with_adult and height >= 120

if not feel_ok:
    print("Сегодня отдохни: на аттракцион пускаем только здоровых.")
elif solo_ok or adult_ok:
    print("Проходи, пристёгивайся — приятного полёта!")
else:
    print("Извини, по росту/возрасту пока нельзя.")

print("-" * 34)
print("Следующий!")
