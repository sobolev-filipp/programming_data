# ===== КАМЕНЬ-НОЖНИЦЫ-БУМАГА (один раунд) =====
# Финал модуля: собираем random + условия + логику and + знакомство со списками.
# Компьютер выбирает случайно ИЗ СПИСКА, мы сравниваем и определяем победителя.

import random

# список — три фигуры в одной "коробке" с ячейками (индексы 0, 1, 2)
options = ["камень", "ножницы", "бумага"]

print("=" * 34)
print("КАМЕНЬ - НОЖНИЦЫ - БУМАГА")
print("=" * 34)

player = input("Твой выбор (камень/ножницы/бумага): ").lower().strip()
comp = random.choice(options)          # случайный элемент списка

print(f"Ты выбрал:        {player}")
print(f"Компьютер выбрал: {comp}")
print("-" * 34)

# Определяем победителя лестницей
if player not in options:              # ввёл НЕ фигуру из списка
    print("Не понял выбор. Пиши: камень, ножницы или бумага.")
elif player == comp:
    print("Ничья!")
elif player == "камень" and comp == "ножницы":
    print("Ты выиграл! Камень тупит ножницы.")
elif player == "ножницы" and comp == "бумага":
    print("Ты выиграл! Ножницы режут бумагу.")
elif player == "бумага" and comp == "камень":
    print("Ты выиграл! Бумага заворачивает камень.")
else:
    print("Компьютер выиграл! В этот раз не повезло.")
