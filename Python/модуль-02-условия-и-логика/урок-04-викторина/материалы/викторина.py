# ===== ВИКТОРИНА ЭРУДИТА =====
# Проект собирает всё из модуля: input, if/elif/else, счёт очков.
# Награда за победу — шутка из внешней библиотеки pyjokes.
# ВАЖНО: перед запуском один раз выполни в терминале:  pip install pyjokes

import pyjokes   # внешняя библиотека — её надо поставить через pip

print("=" * 34)
print("ВИКТОРИНА ЭРУДИТА (5 вопросов)")
print("=" * 34)
print("Отвечай одним словом.\n")

score = 0   # копилка правильных ответов

# --- Вопрос 1 ---
a1 = input("1. Столица Франции? ").lower().strip()
if a1 == "париж":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: Париж.")

# --- Вопрос 2 ---
a2 = input("2. Сколько будет 7 * 8? ").strip()
if a2 == "56":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: 56.")

# --- Вопрос 3 ---
a3 = input("3. Какого цвета небо днём в ясную погоду? ").lower().strip()
if a3 == "голубое" or a3 == "синее":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: голубое.")

# --- Вопрос 4 ---
a4 = input("4. Планета, на которой мы живём? ").lower().strip()
if a4 == "земля":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: Земля.")

# --- Вопрос 5 ---
a5 = input("5. Команда вывода на экран в Python? ").lower().strip()
if a5 == "print" or a5 == "print()":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: print.")

# --- Итог и оценка ---
percent = score / 5 * 100
print("-" * 34)
print(f"Результат: {score} из 5  ({percent:.0f}%)")

if score == 5:
    print("Идеально! Ты настоящий эрудит!")
elif score >= 3:
    print("Хорошо! Крепкий результат.")
else:
    print("Ещё подучись и попробуй снова.")

# --- Награда: шутка из pyjokes за 3+ правильных ---
if score >= 3:
    print("\nТвоя награда — шутка про программистов:")
    print(pyjokes.get_joke(language="en"))
