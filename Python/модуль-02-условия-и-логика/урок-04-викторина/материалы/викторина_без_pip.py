# То же самое, но награда — шутка из встроенного random.choice,
# без pyjokes и без интернета. Запусти, если не удалось pip install.

import random

print("=" * 34)
print("ВИКТОРИНА ЭРУДИТА (5 вопросов)")
print("=" * 34)
print("Отвечай одним словом.\n")

score = 0

a1 = input("1. Столица Франции? ").lower().strip()
if a1 == "париж":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: Париж.")

a2 = input("2. Сколько будет 7 * 8? ").strip()
if a2 == "56":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: 56.")

a3 = input("3. Какого цвета небо днём в ясную погоду? ").lower().strip()
if a3 == "голубое" or a3 == "синее":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: голубое.")

a4 = input("4. Планета, на которой мы живём? ").lower().strip()
if a4 == "земля":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: Земля.")

a5 = input("5. Команда вывода на экран в Python? ").lower().strip()
if a5 == "print" or a5 == "print()":
    print("Верно!")
    score += 1
else:
    print("Неверно. Правильно: print.")

percent = score / 5 * 100
print("-" * 34)
print(f"Результат: {score} из 5  ({percent:.0f}%)")

if score == 5:
    print("Идеально! Ты настоящий эрудит!")
elif score >= 3:
    print("Хорошо! Крепкий результат.")
else:
    print("Ещё подучись и попробуй снова.")

# Награда — своя мини-база шуток (без внешних библиотек)
jokes = [
    "Почему программисты путают Хэллоуин и Рождество? Потому что 31 OCT = 25 DEC.",
    "Сколько программистов нужно, чтобы вкрутить лампочку? Ни одного — это аппаратная проблема.",
    "Программист застрял в душе: на шампуне было написано «намылить, смыть, повторить».",
]
if score >= 3:
    print("\nТвоя награда — шутка:")
    print(random.choice(jokes))
