# ---- 1. Функция БЕЗ параметров: описали команду один раз ----

def ramka():
    # всё, что с отступом, - это ТЕЛО функции (что она делает)
    print("+-----------+")
    print("|  ПРИВЕТ!  |")
    print("+-----------+")


# ---- 2. Вызовы: зовём команду по имени, сколько нужно ----
print("Старт программы")
ramka()          # вызвали первый раз
ramka()          # и ещё раз - код не копировали!
print("Между рамками")
ramka()
print("Конец программы")

print("-" * 30)

# ---- 3. Функция С ПАРАМЕТРОМ: одна команда - разный результат ----

def privet(name):
    # name - это параметр: окошко, куда попадёт то, что передали в скобках
    print("Привет,", name + "!")
    print("Рад тебя видеть.")


privet("Аня")     # внутри name = "Аня"
privet("Боря")    # внутри name = "Боря"

