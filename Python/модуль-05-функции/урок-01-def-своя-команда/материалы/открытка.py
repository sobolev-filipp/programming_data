# Одна функция-открытка, а поздравить можно кого угодно и с чем угодно.
# В print() нет эмодзи - иначе падает на Windows (cp1251).


def otkrytka(name, prazdnik, vozrast):
    # три параметра = три окошка на входе: имя, праздник, возраст
    print("*" * 28)
    print("  Дорогой друг:", name)
    print("  Поздравляю с:", prazdnik)
    print("  Тебе теперь:", vozrast, "лет!")
    print("*" * 28)


# Зовём с разными данными - открытка каждый раз своя:
otkrytka("Аня", "Днём рождения", 12)
print()
otkrytka("Боря", "Новым годом", 13)
print()

