# ===== ЁЛОЧКА ИЗ ЗВЁЗДОЧЕК =====
# for + range + умножение строки: "*" * k печатает k звёздочек, " " * k — k пробелов.
# Каждая строка: слева пробелы, потом НЕЧЁТНОЕ число звёзд (1, 3, 5, ...).

height = int(input("Высота ёлочки (например 5): "))

for i in range(1, height + 1):
    spaces = " " * (height - i)     # отступ слева — чтобы получился треугольник
    stars = "*" * (2 * i - 1)       # 1, 3, 5, 7, ... звёзд
    print(spaces + stars)

# ствол под ёлкой
print(" " * (height - 1) + "|")
