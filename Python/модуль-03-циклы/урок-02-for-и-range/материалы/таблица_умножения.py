# ===== ТАБЛИЦА УМНОЖЕНИЯ =====
# Новое: цикл for и range — повторяем действие известное число раз.
# for i in range(1, 11) даёт i = 1, 2, 3, ..., 10 (число 11 НЕ входит).

n = int(input("На какое число таблицу умножения? "))

print(f"Таблица умножения на {n}:")
for i in range(1, 11):          # i пробегает 1, 2, ..., 10
    print(f"{n} x {i} = {n * i}")

print("Готово!")
