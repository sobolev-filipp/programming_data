# ===== КАК РАБОТАЕТ ПЕРЕБОР (for) =====
# Главная идея: for берёт из коллекции ПО ОДНОМУ элементу
# и выполняет тело для каждого. Коллекция = список, строка, range.

# 1) перебор СПИСКА — по элементам, без индексов
games = ["Minecraft", "Roblox", "Sims"]
print("Мои игры:")
for game in games:
    print("-", game)

# 2) перебор СТРОКИ — по символам (буквам)
word = "Привет"
print("Буквы слова:")
for letter in word:
    print(letter)

# 3) range — числа по порядку / повторить N раз
print("Числа от 1 до 5:")
for i in range(1, 6):
    print(i)

# 4) range со ШАГОМ + приём end=" " (печать в одну строку)
print("Чётные до 10:", end=" ")
for i in range(2, 11, 2):
    print(i, end=" ")      # end=" " — не переводить строку, а ставить пробел
print()                    # пустой print() — перевод строки в конце

# 5) обратный отсчёт через отрицательный шаг
print("Обратный отсчёт:", end=" ")
for i in range(5, 0, -1):
    print(i, end=" ")
print("Пуск!")
