# ===== BREAK и CONTINUE =====
# break    — выйти из цикла ДОСРОЧНО (нашли — дальше не нужно).
# continue — ПРОПУСТИТЬ текущий виток и перейти к следующему.

# --- break: ищем первое число, делящееся на 7 ---
print("Первое число, кратное 7:")
for n in range(1, 100):
    if n % 7 == 0:
        print("Нашли:", n)
        break                 # выходим — искать дальше незачем

# --- continue: печатаем 1..10, но пропускаем кратные 3 ---
print("Числа 1..10, кроме кратных 3:")
for n in range(1, 11):
    if n % 3 == 0:
        continue              # пропускаем этот виток (3, 6, 9)
    print(n, end=" ")
print()

# --- break во вложенном цикле выходит ТОЛЬКО из внутреннего ---
print("Пары, пока сумма <= 4:")
for a in range(1, 4):
    for b in range(1, 4):
        if a + b > 4:
            break             # прерываем внутренний цикл
        print(f"({a},{b})", end=" ")
    print()
