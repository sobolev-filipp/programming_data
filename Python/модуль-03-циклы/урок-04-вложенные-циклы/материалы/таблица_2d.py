# ===== ТАБЛИЦА УМНОЖЕНИЯ 10x10 (вложенные циклы) =====
# Внешний цикл — строки, внутренний — столбцы.
# Для КАЖДОЙ строки внутренний цикл проходит все 10 столбцов.

for row in range(1, 11):                 # 1) внешний: строки 1..10
    for col in range(1, 11):             # 2) внутренний: столбцы 1..10
        print(f"{row * col:4}", end="")  # число в поле шириной 4, без переноса
    print()                              # конец строки — перевод строки
