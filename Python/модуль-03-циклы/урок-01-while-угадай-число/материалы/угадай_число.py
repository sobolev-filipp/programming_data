# ===== УГАДАЙ ЧИСЛО =====
# Компьютер загадывает число от 1 до 100, а мы угадываем.
# Новое в этом уроке: цикл while, выход из цикла break, счётчик попыток.
#
# Как это работает:
#   - random.randint(1, 100) загадывает секретное число;
#   - while True повторяет вопрос, пока не угадаем;
#   - на каждой попытке считаем attempts += 1 и подсказываем "больше/меньше";
#   - как только guess == secret — печатаем победу и break выходит из цикла.

import random

secret = random.randint(1, 100)   # секретное число (сам его не видишь)
attempts = 0                      # копилка попыток

print("=" * 32)
print("УГАДАЙ ЧИСЛО ОТ 1 ДО 100")
print("=" * 32)

while True:
    guess = int(input("Твой вариант: "))
    attempts += 1                 # была ещё одна попытка

    if guess < secret:
        print("Больше!")
    elif guess > secret:
        print("Меньше!")
    else:
        print(f"Верно! Ты угадал число {secret} за {attempts} попыток.")
        break                     # угадали — выходим из цикла

print("-" * 32)
print("Спасибо за игру!")
