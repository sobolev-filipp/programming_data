# Телефонная книга: имя -> номер телефона.
# Показывает словарь на «живом» проекте: добавление, поиск, безопасный доступ, перебор.

# Стартовая книга (несколько контактов)
book = {
    "Аня": "555-01-23",
    "Боря": "555-04-56",
    "Вера": "555-07-89",
}

print("=== ТЕЛЕФОННАЯ КНИГА ===")
print("Контактов в книге:", len(book))
print()

# 1. Добавляем новые контакты (ключ -> значение)
book["Гена"] = "555-10-11"
book["Дима"] = "555-12-13"
print("Добавили Гену и Диму. Теперь контактов:", len(book))
print()

# 2. Показываем всю книгу (перебор по ключам)
print("Все контакты:")
for name in book:
    print(f"  {name}: {book[name]}")
print()

# 3. Ищем телефон по имени. .get() не падает, если имени нет.
who = "Вера"
print(f"Телефон {who}: {book.get(who, 'не найден')}")

who = "Женя"
print(f"Телефон {who}: {book.get(who, 'не найден')}")
print()

# 4. Проверяем, есть ли человек в книге
name = "Боря"
if name in book:
    print(f"{name} есть в книге, номер {book[name]}")
else:
    print(f"{name} в книге нет")
print()

# 5. Изменяем номер (человек сменил телефон) и удаляем контакт
book["Аня"] = "555-99-99"        # тот же ключ -> новое значение
del book["Дима"]                 # удалить контакт
print("Аня сменила номер, Диму удалили.")
print("Итоговая книга:")
for name in book:
    print(f"  {name}: {book[name]}")
