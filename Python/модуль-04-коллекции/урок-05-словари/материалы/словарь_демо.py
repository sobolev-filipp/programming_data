# Словарь (dict) — хранит данные парами КЛЮЧ -> ЗНАЧЕНИЕ.
# Ключ как бирка: по нему сразу достаём значение (не по номеру-индексу).

# 1. СОЗДАНИЕ словаря и доступ по ключу
book = {"Аня": "555-01", "Боря": "555-02", "Вера": "555-03"}
print("Словарь:", book)
print("Телефон Бори:", book["Боря"])     # достаём значение по ключу
print("Всего контактов:", len(book))     # сколько пар
print("-" * 40)

# 2. НЕТ ключа — квадратные скобки роняют программу (KeyError)
try:
    print(book["Кот"])                    # такого ключа нет!
except KeyError as error:
    print("Нет такого ключа:", error)
print("-" * 40)

# 3. .get() — безопасный доступ: вернёт None (или запасное значение) вместо ошибки
print("get Аня:", book.get("Аня"))        # 555-01
print("get Кот:", book.get("Кот"))        # None
print("get Кот с запасным:", book.get("Кот", "нет в книге"))
print("-" * 40)

# 4. ДОБАВИТЬ и ИЗМЕНИТЬ — одинаковая запись d[ключ] = значение
book["Гена"] = "555-04"                    # ключа не было -> добавили
book["Аня"] = "555-99"                     # ключ был -> заменили значение
print("После добавления/замены:", book)
print("-" * 40)

# 5. ПРОВЕРКА ключа и УДАЛЕНИЕ
print("Есть Вера?", "Вера" in book)        # True
print("Есть Кот?", "Кот" in book)          # False
del book["Боря"]                           # удалить по ключу
removed = book.pop("Гена")                 # удалить и вернуть значение
print("pop вернул:", removed)
print("После удаления:", book)
print("-" * 40)

# 6. Три способа посмотреть на словарь: keys / values / items
print("Ключи:", list(book.keys()))         # имена
print("Значения:", list(book.values()))    # телефоны
print("Пары:", list(book.items()))         # (ключ, значение)
print("-" * 40)

# 7. ПЕРЕБОР по ключам: for идёт по ключам, значение берём по ключу
print("Телефонная книга:")
for name in book:
    print(f"  {name}: {book[name]}")
print("-" * 40)

# 8. Значением может быть ЧИСЛО (инвентарь: предмет -> количество)
inventory = {"меч": 1, "зелье": 5, "монета": 120}
inventory["зелье"] += 2                     # стало на 2 больше
print("Инвентарь:", inventory)
print("Зелий:", inventory["зелье"])         # 7
