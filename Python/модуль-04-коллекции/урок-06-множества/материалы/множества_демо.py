# Множество (set) — коллекция УНИКАЛЬНЫХ элементов без порядка.
# Главное: дубли исчезают сами, а порядок не хранится.

# 1. СОЗДАНИЕ множества и удаление дублей
tags = {"питон", "код", "питон", "игра", "код"}   # повторы в скобках
print("Множество:", tags)          # каждый элемент один раз
print("Сколько разных:", len(tags))

# 2. Из СПИСКА в множество — быстрый способ убрать повторы
words = ["кот", "пёс", "кот", "кот", "пёс"]
unique = set(words)
print("Было в списке:", len(words), "-> разных:", len(unique))
print("Уникальные:", unique)
print("-" * 40)

# 3. ПУСТОЕ множество — это set(), а НЕ {} (это пустой словарь!)
empty = set()
print("Пустое множество:", empty, "| тип:", type(empty).__name__)
print("-" * 40)

# 4. Проверка in и добавление/удаление
print("питон есть?", "питон" in tags)     # True
print("java есть?", "java" in tags)       # False
tags.add("java")                          # добавить элемент
tags.add("код")                           # дубль не добавится
tags.discard("игра")                      # удалить (без ошибки, если нет)
print("После изменений:", tags)
print("-" * 40)

# 5. ОПЕРАЦИИ над множествами (теги двух постов)
post1 = {"питон", "код", "игра"}
post2 = {"код", "игра", "музыка"}
print("Все теги вместе (объединение |):", post1 | post2)
print("Общие теги (пересечение &):", post1 & post2)
print("Только у post1 (разность -):", post1 - post2)
print("-" * 40)

# 6. То же словами-методами (читается понятнее)
print("union:", post1.union(post2))
print("intersection:", post1.intersection(post2))
print("difference:", post1.difference(post2))
