# «Нарезка данных»: срезы решают реальные задачи над списком и строкой.

steps = [8200, 5400, 12000, 9100, 7600, 15300, 6800]   # шаги по дням недели
days = ["Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс"]

print("Шаги за неделю:", steps)
print("-" * 45)

# Будни и выходные — срезом
print("Будни (Пн-Пт):", steps[:5])
print("Выходные (Сб-Вс):", steps[5:])
print("-" * 45)

# Последние 3 дня
print("Последние 3 дня:", steps[-3:])
print("-" * 45)

# Топ-3 активных дня: сортируем по убыванию и берём первые три срезом
top3 = sorted(steps, reverse=True)[:3]
print("Топ-3 по шагам:", top3)
print("-" * 45)

# Каждый второй день
print("Через день:", steps[::2])
print("-" * 45)

# Разворот: неделя задом наперёд
print("С конца недели:", steps[::-1])
print("Дни с конца:", days[::-1])
print("-" * 45)

# Строка наоборот и проверка на палиндром
word = input("Слово для проверки на палиндром: ").lower()
reversed_word = word[::-1]
if word == reversed_word:
    print(word, "- палиндром! Читается одинаково в обе стороны.")
else:
    print(word, "- не палиндром. Наоборот:", reversed_word)

# Безопасная копия списка через срез [:]
backup = steps[:]
backup.sort()
print("Копия отсортирована:", backup)
print("Оригинал цел:", steps)
