# Кортеж (tuple) — «замороженный» список: те же элементы, но МЕНЯТЬ нельзя.
# Каждый блок показывает свойство кортежа.

point = (3, 5)              # кортеж из двух чисел — в круглых скобках
print("Кортеж:", point)
print("Тип:", type(point))
print("По индексу: x =", point[0], "y =", point[1])
print("Длина:", len(point))
print("-" * 40)

# 1. НЕИЗМЕНЯЕМОСТЬ — попытка изменить даёт ошибку
try:
    point[0] = 99          # так нельзя!
except TypeError as error:
    print("Изменить нельзя:", error)
print("-" * 40)

# 2. РАСПАКОВКА — разложить кортеж по переменным
x, y = point
print("Распаковка: x =", x, ", y =", y)

name, age, city = ("Аня", 12, "Москва")
print(f"{name}, {age} лет, {city}")
print("-" * 40)

# 3. ОБМЕН значениями через кортеж (без временной переменной)
a, b = 10, 20
a, b = b, a
print("После обмена: a =", a, ", b =", b)
print("-" * 40)

# 4. Кортеж в ЦИКЛЕ (список кортежей) + распаковка прямо в for
points = [(0, 0), (3, 4), (6, 0)]
print("Точки треугольника:")
for px, py in points:      # каждый кортеж сразу распаковывается в px, py
    print(f"  x={px}, y={py}")
print("-" * 40)

# 5. Кортеж vs список
colors_list = ["красный", "жёлтый"]   # список — можно менять
rgb = (255, 128, 0)                   # кортеж — цвет-константа, менять НЕ нужно
colors_list.append("зелёный")         # список растёт
print("Список (изменяемый):", colors_list)
print("Кортеж-константа RGB:", rgb)
print("-" * 40)

# 6. 🎓 Кортеж может быть КЛЮЧОМ словаря (список — не может)
capitals = {("Россия", "столица"): "Москва", ("Франция", "столица"): "Париж"}
print("Ключ-кортеж:", capitals[("Россия", "столица")])
