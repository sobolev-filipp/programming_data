# «Координаты и константы»: кортежи удобны для точек, цветов и фиксированных наборов.

# Точки на карте — список кортежей (x, y)
route = [(0, 0), (2, 3), (5, 3), (5, 7), (8, 9)]
print("Маршрут из", len(route), "точек")

# Пройдём маршрут с распаковкой и посчитаем «шаги» между точками
step = 1
for x, y in route:
    print(f"  точка {step}: x={x}, y={y}")
    step += 1
print("-" * 40)

# Длина одного шага (по прямой) между первыми двумя точками
x1, y1 = route[0]
x2, y2 = route[1]
distance = ((x2 - x1) ** 2 + (y2 - y1) ** 2) ** 0.5
print(f"Расстояние (0,0)->(2,3): {round(distance, 2)}")
print("-" * 40)

# Цвета как кортежи-константы RGB (красный, зелёный, синий)
BLACK = (0, 0, 0)
ORANGE = (234, 88, 12)
SKY = (135, 206, 235)
print("ORANGE =", ORANGE, "-> красного:", ORANGE[0])
print("-" * 40)

# Функция может ВЕРНУТЬ несколько значений — это кортеж
def min_max(numbers):
    return min(numbers), max(numbers)   # вернётся кортеж (min, max)

low, high = min_max([7, 2, 9, 4])       # распаковываем результат
print("min =", low, ", max =", high)
print("-" * 40)

# Обмен координат местами через кортеж (отражение по диагонали)
x, y = 3, 8
x, y = y, x
print("После обмена x,y:", (x, y))
print("-" * 40)

# 🎓 Кортеж-ключ: счёт матчей между командами
scores = {
    ("Спартак", "Зенит"): (2, 1),
    ("ЦСКА", "Динамо"): (0, 0),
}
print("Спартак–Зенит:", scores[("Спартак", "Зенит")])
