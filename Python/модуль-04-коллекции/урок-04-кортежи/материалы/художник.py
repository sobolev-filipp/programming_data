import turtle
import time

# ---------- НАСТРОЙКА ХОЛСТА (можно не читать) ----------
_UNIT = 30
_LIM = 8
_STEP_DELAY = 0.05

_screen = turtle.Screen()
_screen.setup(620, 620)
_screen.title("Художник по точкам-кортежам")
turtle.tracer(0, 0)

_grid = turtle.Turtle(visible=False)
_grid.speed(0)
_grid.pencolor("#e8edf3")
for _i in range(-_LIM, _LIM + 1):
    _grid.penup(); _grid.goto(_i * _UNIT, -_LIM * _UNIT); _grid.pendown(); _grid.goto(_i * _UNIT, _LIM * _UNIT)
    _grid.penup(); _grid.goto(-_LIM * _UNIT, _i * _UNIT); _grid.pendown(); _grid.goto(_LIM * _UNIT, _i * _UNIT)
# оси
_grid.pencolor("#94a3b8"); _grid.pensize(2)
_grid.penup(); _grid.goto(-_LIM * _UNIT, 0); _grid.pendown(); _grid.goto(_LIM * _UNIT, 0)
_grid.penup(); _grid.goto(0, -_LIM * _UNIT); _grid.pendown(); _grid.goto(0, _LIM * _UNIT)
_grid.penup()

_pen = turtle.Turtle()
_pen.hideturtle(); _pen.speed(0)
_pen.pensize(3); _pen.pencolor("#ea580c")
_pen.penup()

# ---- базовая фигура: список ВЕРШИН-КОРТЕЖЕЙ ----
house = [(-2, -2), (2, -2), (2, 1), (0, 3), (-2, 1), (-2, -2)]


def _sc(point):
    return point[0] * _UNIT, point[1] * _UNIT


def move_to(point):
    """Перенести перо в точку без линии (начать новую фигуру)."""
    _pen.penup()
    _pen.goto(_sc(point))
    turtle.update()


def line_to(point):
    """Провести линию в точку от текущего положения."""
    _pen.pendown()
    _pen.goto(_sc(point))
    turtle.update(); time.sleep(_STEP_DELAY)


def dot(point, color="#2563eb"):
    """Поставить точку-маркер в вершине."""
    _pen.penup(); _pen.goto(_sc(point))
    _pen.dot(12, color)
    turtle.update()


turtle.update()

