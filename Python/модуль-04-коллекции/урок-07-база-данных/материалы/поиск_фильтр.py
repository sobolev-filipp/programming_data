# Поиск, фильтр, итоги и сортировка по полю в списке словарей.

heroes = [
    {"имя": "Рыцарь", "класс": "воин", "hp": 100, "уровень": 5},
    {"имя": "Маг",    "класс": "маг",  "hp": 70,  "уровень": 7},
    {"имя": "Лучник", "класс": "воин", "hp": 80,  "уровень": 4},
    {"имя": "Вор",    "класс": "плут", "hp": 60,  "уровень": 6},
]

# 1. ПОИСК записи по имени: идём по списку и сравниваем поле "имя"
искомое = "Маг"
найден = None
for hero in heroes:
    if hero["имя"] == искомое:
        найден = hero
if найден is not None:
    print(f"Нашли: {найден['имя']}, hp {найден['hp']}")
else:
    print("Такого героя нет")
print("-" * 40)

# 2. ФИЛЬТР: собрать в новый список всех «воинов»
воины = []
for hero in heroes:
    if hero["класс"] == "воин":
        воины.append(hero)
print("Воинов:", len(воины))
for hero in воины:
    print("  ", hero["имя"])
print("-" * 40)

# 3. ИТОГИ по полю: сумма и среднее hp (значения полей — числа)
сумма_hp = 0
for hero in heroes:
    сумма_hp += hero["hp"]
print("Всего hp у отряда:", сумма_hp)
print("Средний hp:", round(сумма_hp / len(heroes), 1))
print("-" * 40)

# 4. ЧЕМПИОН: запись с наибольшим hp (перебор с запоминанием рекордсмена)
чемпион = heroes[0]
for hero in heroes:
    if hero["hp"] > чемпион["hp"]:
        чемпион = hero
print(f"Больше всех hp у: {чемпион['имя']} ({чемпион['hp']})")
print("-" * 40)

# 5. СОРТИРОВКА по полю без lambda: собираем пары (значение_поля, имя) и сортируем.
#    Кортежи сравниваются по первому элементу — значит по hp.
пары = []
for hero in heroes:
    пары.append((hero["hp"], hero["имя"]))
пары.sort(reverse=True)                 # по убыванию hp
print("Рейтинг по hp:")
for hp, имя in пары:
    print(f"  {имя}: {hp}")
