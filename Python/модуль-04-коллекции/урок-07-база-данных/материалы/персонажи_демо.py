# Мини-база данных = СПИСОК СЛОВАРЕЙ.
# Один персонаж — это словарь (запись). Все персонажи — список таких словарей (таблица).

# Таблица персонажей: список словарей с одинаковыми ключами
heroes = [
    {"имя": "Рыцарь", "класс": "воин", "hp": 100, "уровень": 5},
    {"имя": "Маг",    "класс": "маг",  "hp": 70,  "уровень": 7},
    {"имя": "Лучник", "класс": "воин", "hp": 80,  "уровень": 4},
]

# 1. ОДНА запись — это словарь; поле достаём по ключу
print("Первый герой:", heroes[0])
print("Его имя:", heroes[0]["имя"])       # список -> [0], словарь -> ["имя"]
print("Всего героев:", len(heroes))
print("-" * 40)

# 2. ПЕРЕБОР таблицы: на каждом шаге hero — это словарь-запись
print("Список героев:")
for hero in heroes:
    print(f"  {hero['имя']} ({hero['класс']}) — hp {hero['hp']}, ур. {hero['уровень']}")
print("-" * 40)

# 3. ДОБАВИТЬ запись — просто append словаря
heroes.append({"имя": "Вор", "класс": "плут", "hp": 60, "уровень": 6})
print("Добавили Вора. Теперь героев:", len(heroes))
print("-" * 40)

# 4. ИЗМЕНИТЬ поле у записи (герой получил урон)
heroes[0]["hp"] = heroes[0]["hp"] - 30     # Рыцарь потерял 30 hp
print("У Рыцаря стало hp:", heroes[0]["hp"])
print("-" * 40)

# 5. УДАЛИТЬ запись по индексу
removed = heroes.pop(2)                     # убрать Лучника (индекс 2)
print("Удалили:", removed["имя"])
print("Осталось героев:", len(heroes))
