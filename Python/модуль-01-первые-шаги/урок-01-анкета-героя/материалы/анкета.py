# ===== АНКЕТА ГЕРОЯ =====
# Эталонный код урока 1. Запусти: Run ▶ (PyCharm / VS Code) или  python анкета.py

# 1. Спрашиваем данные у пользователя
name = input("Как тебя зовут? ")
age = int(input("Сколько тебе лет? "))   # int() — чтобы возраст был числом
game = input("Любимая игра? ")
city = input("Из какого ты города? ")

# 2. Считаем возраст через 10 лет
age_future = age + 10

# 3. Красиво выводим анкету (f-строки + рамка из "=")
print()
print("=" * 27)
print("АНКЕТА ГЕРОЯ")
print("=" * 27)
print(f"Привет, {name} из города {city}!")
print(f"Тебе сейчас {age} лет, а через 10 будет {age_future}.")
print(f"Твоя любимая игра — {game}. Отличный выбор!")
